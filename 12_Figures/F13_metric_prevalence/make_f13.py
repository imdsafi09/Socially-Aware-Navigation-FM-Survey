"""F13 - What current FM social-navigation research measures: metric families by the number of direct papers using them,
grouped by evaluation level, with each family's main blind spot. Replaces the metric-family table in the main text
(full table -> supplementary Table S10). Data: 11_Tables/T8_evaluation_metrics.csv, generated by 11_Tables/build_tables.py from
07_Literature_Analysis/evaluation_metrics_matrix.csv (family = keyword match on metric names, documented in build_tables.py).
EVIDENCE_MAP.md is written by this script. Print scale: 516 pt canvas; lettering >= 7 pt."""
import os, sys, csv, re
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from figlib import *
import cairo
H = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, '11_Tables', 'T8_evaluation_metrics.csv')
T = list(csv.DictReader(open(SRC)))
ND = int(T[0]['Direct papers using family'].split('/')[1])   # number of direct papers (denominator of every family)
GROUPS = [('Model-level', ('Model',)), ('Model or robot', ('Model / robot',)), ('Robot-level', ('Robot',)), ('Human-centred', ('Robot (human-centred)',)), ('System / deployment', ('System',))]
TONE = {'Model-level': (0.62, 0.72, 0.84), 'Model or robot': (0.45, 0.58, 0.74), 'Robot-level': (0.20, 0.36, 0.55), 'Human-centred': OK['orange'], 'System / deployment': (0.55, 0.55, 0.55)}
PAT = {'Human-centred': 'diag', 'System / deployment': 'dots'}
rows = []
for g, lv in GROUPS:
    sel = [r for r in T if r['Level'] in lv]
    for r in sel:
        n, d = map(int, r['Direct papers using family'].split('/')); r['_n'], r['_d'] = n, d
    rows.append((g, sorted(sel, key=lambda r: -r['_n'])))
assert sum(len(s) for _, s in rows) == len(T), 'every family must be in one level group'
_m = cairo.Context(cairo.RecordingSurface(cairo.CONTENT_COLOR_ALPHA, None))
def tw(s):
    _m.select_font_face(FONT, cairo.FONT_SLANT_ITALIC, cairo.FONT_WEIGHT_NORMAL); _m.set_font_size(eff(7)); return _m.text_extents(s).x_advance
def wrap(s, w):
    out, ln = [], ''
    for x in s.split(' '):
        t = (ln + ' ' + x).strip()
        if tw(t) <= w or not ln: ln = t
        else: out.append(ln); ln = x
    return out + [ln]
def clean(s): return re.sub(r'\s*\(SAF\d|\s*\(SPA\d|\s*\(EXP\d.*?\)', '', s).replace('$\\geq$', '≥').replace('>=', '≥')
W = 516; XN, XB, BW, XT, TWID = 2, 160, 120, 316, 198; LP = 8.4
def draw(c):
    text(c, XN, 9, 'Metric family', 7.4, True); text(c, XB, 9, f'Direct papers using the family (of {ND})', 7.4, True); text(c, XT, 9, 'What it cannot show', 7.4, True)
    y = 18
    for g, sel in rows:
        if not sel: continue
        text(c, XN, y + 8, g, 7, True, 'left', (0.30, 0.30, 0.30)); y += 11
        for r in sel:
            lines = wrap(clean(r['What it fails to measure']), TWID)
            h = max(11.5, LP * len(lines) + 3)
            text(c, XN + 6, y + 8, r['Metric family'], 7, False, 'left', 'black')
            pattern(c, XB, y + 2.2, BW * r['_n'] / 25, 7.2, TONE[g], PAT.get(g, 'solid'), step=2.2, lw=0.45, color=(1, 1, 1))
            text(c, XB + BW * r['_n'] / 25 + 3, y + 8, str(r['_n']), 7, False, 'left', 'black')
            for k, ln in enumerate(lines): text(c, XT, y + 8 + k * LP, ln, 7, False, 'left', (0.30, 0.30, 0.30), italic=True)
            y += h
        y += 2
    global HT; HT = y + 2
draw(cairo.Context(cairo.RecordingSurface(cairo.CONTENT_COLOR_ALPHA, None)))
render(draw, W, HT, os.path.join(H, 'F13_metric_prevalence'))
M = ['# Evidence map: F13 metric prevalence (generated by make_f13.py; do not edit)', '',
     f'Plotted variable: number of direct papers (of {ND}) with at least one metric definition in the family.',
     'Source matrix: `07_Literature_Analysis/evaluation_metrics_matrix.csv`.',
     'Families are assigned by the documented keyword patterns in `11_Tables/build_tables.py` (table T8) and written to `11_Tables/T8_evaluation_metrics.csv`, which this script reads. The level grouping and the "what it cannot show" text are the curated T8 columns. No value is typed by hand.', '',
     '| Level group | Metric family | Numerator (direct papers) | Denominator | Blind spot shown |', '|---|---|---|---|---|']
for g, sel in rows:
    for r in sel: M.append(f"| {g} | {r['Metric family']} | {r['_n']} | {r['_d']} | {clean(r['What it fails to measure'])} |")
M += ['', 'Generation script: `12_Figures/F13_metric_prevalence/make_f13.py` (pycairo; deterministic).']
open(os.path.join(H, 'EVIDENCE_MAP.md'), 'w').write('\n'.join(M) + '\n')
print('F13 done')
